namespace UniversalCraftingFramework::QuestRecipeGuard {
    void Initialize() {
        g_protected.clear();
        auto* handler = RE::TESDataHandler::GetSingleton();
        if (!handler) {
            SKSE::log::error("[QuestRecipeGuard] Data handler missing; guard unavailable.");
            return;
        }
        for (const auto& key : kQuestRecipes) {
            auto* recipe = handler->LookupForm<RE::BGSConstructibleObject>(key.localID, key.plugin.data());
            if (recipe) g_protected.insert(recipe);
        }
        SKSE::log::info("[QuestRecipeGuard] Protected {} recipes from {} diagnostic entries (read-only classification).",
                        g_protected.size(), std::size(kQuestRecipes));
    }
    bool IsProtected(const RE::BGSConstructibleObject* recipe) {
        return recipe && g_protected.contains(recipe);
    }
}
